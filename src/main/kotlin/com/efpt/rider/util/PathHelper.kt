package com.efpt.rider.util

import java.io.File
import java.nio.file.Path
import java.nio.file.Paths

/** Port of RevEng.Common.PathHelper / PathExtensions / SqlProjHelper path utilities (cross-platform). */
object PathHelper {
    const val HEADER = "// <auto-generated> This file has been auto generated by EF Core Power Tools. </auto-generated>"

    /**
     * Resolves [outputPath] relative to [fullName] (a project file or a directory).
     * Absolute paths, UNC paths and "..\" segments are handled like the original.
     */
    fun getAbsPath(outputPath: String, fullName: String): String {
        val normalized = outputPath.replace('\\', File.separatorChar).replace('/', File.separatorChar)
        if (outputPath.startsWith("\\\\") || outputPath.startsWith("//")) return outputPath
        val p = Paths.get(normalized)
        if (p.isAbsolute) return p.normalize().toString()
        val base = File(fullName)
        val folder = if (base.isDirectory) base.toPath() else (base.toPath().parent ?: base.toPath())
        return folder.resolve(p).normalize().toString()
    }

    fun getNamespaceFromOutputPath(directoryPath: String, projectDir: String, rootNamespace: String?): String? {
        val sub = subNamespaceFromOutputPath(projectDir, directoryPath)
        return if (sub.isNullOrEmpty()) rootNamespace else "$rootNamespace.$sub"
    }

    private fun subNamespaceFromOutputPath(projectDir: String, outputDir: String): String? {
        if (!outputDir.startsWith(projectDir)) return null
        val subPath = outputDir.substring(projectDir.length)
        return if (subPath.isNotBlank()) subPath.split('\\', '/').filter { it.isNotEmpty() }.joinToString(".") else null
    }

    /** Relative path from [fromDirectory] to [toPath]; returns [toPath] unchanged when on another root. */
    fun getRelativePath(fromDirectory: String, toPath: String): String = try {
        Path.of(fromDirectory).toAbsolutePath().normalize().relativize(Path.of(toPath).toAbsolutePath().normalize()).toString()
    } catch (_: IllegalArgumentException) {
        toPath
    }

    /** SqlProjHelper.SetRelativePathForSqlProj. */
    fun setRelativePathForSqlProj(uiHint: String, projectDirectory: String): String? {
        var hint = uiHint
        if (Path.of(hint).isAbsolute) hint = getRelativePath(projectDirectory, hint)
        return if (Path.of(hint).isAbsolute) null else hint
    }

    /** SqlProjHelper.GetFullPathForSqlProj. */
    fun getFullPathForSqlProj(uiHint: String, projectDirectory: String?): String {
        if (projectDirectory.isNullOrEmpty()) return uiHint
        return if (isDefinitionPath(uiHint)) getAbsPath(uiHint, projectDirectory) else uiHint
    }

    fun isDefinitionPath(path: String) =
        path.endsWith(".sqlproj", true) || path.endsWith(".csproj", true) || path.endsWith(".dacpac", true)

    fun fileNameWithoutExtension(path: String): String = File(path).nameWithoutExtension
}
